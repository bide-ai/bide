#!/usr/bin/env bash
# brew-formula.sh: write the Homebrew formula for a bide release, from the release's checksums.
#
#   scripts/brew-formula.sh vX.Y.Z CHECKSUMS     (prints Formula/bide.rb for bide-ai/homebrew-tap)
#   scripts/brew-formula.sh --self-test
#
# The formula installs the bide binary from the release archives (macOS and Linux, amd64 and
# arm64), each pinned by the sha256 that the release's checksums.txt lists. It is a formula, not a
# cask, so Linux keeps Homebrew; goreleaser's formula support is deprecated, so the release
# workflow runs this script instead.
set -euo pipefail

REPO=${BIDE_GITHUB_REPO:-bide-ai/bide}

die() { echo "brew-formula: error: $*" >&2; exit 1; }

# sum checksums archive: the sha256 checksums lists for archive.
sum() {
  local s
  s=$(awk -v f="$2" '$2 == f {print $1}' "$1")
  [[ "$s" =~ ^[0-9a-f]{64}$ ]] || die "checksums lists no sha256 for $2"
  echo "$s"
}

formula() {
  local tag=$1 sums=$2 v=${1#v} url da dr la lr
  url="https://github.com/$REPO/releases/download/$tag"
  # Each sum is read before the formula is printed, so a missing one stops here with nothing written.
  da=$(sum "$sums" "bide_${v}_darwin_amd64.tar.gz") || return 1
  dr=$(sum "$sums" "bide_${v}_darwin_arm64.tar.gz") || return 1
  la=$(sum "$sums" "bide_${v}_linux_amd64.tar.gz") || return 1
  lr=$(sum "$sums" "bide_${v}_linux_arm64.tar.gz") || return 1
  cat <<RUBY
# typed: false
# frozen_string_literal: true

# Generated by scripts/brew-formula.sh in bide-ai/bide from the $tag release's checksums.txt.
# Do not edit by hand: the release workflow rewrites it for each release.
class Bide < Formula
  desc "Durable, provable agents: demo, run viewer, flow checks and offline audit verification"
  homepage "https://bide-ai.com"
  version "$v"
  license "Apache-2.0"

  on_macos do
    if Hardware::CPU.intel?
      url "$url/bide_${v}_darwin_amd64.tar.gz"
      sha256 "$da"
    end
    if Hardware::CPU.arm?
      url "$url/bide_${v}_darwin_arm64.tar.gz"
      sha256 "$dr"
    end
  end

  on_linux do
    if Hardware::CPU.intel? && Hardware::CPU.is_64_bit?
      url "$url/bide_${v}_linux_amd64.tar.gz"
      sha256 "$la"
    end
    if Hardware::CPU.arm? && Hardware::CPU.is_64_bit?
      url "$url/bide_${v}_linux_arm64.tar.gz"
      sha256 "$lr"
    end
  end

  def install
    bin.install "bide"
  end

  test do
    assert_match "bide v#{version}", shell_output("#{bin}/bide version")
    assert_match "verify-evidence", shell_output("#{bin}/bide help audit")
  end
end
RUBY
}

self_test() {
  local tmp ok=true out
  tmp=$(mktemp -d)
  for t in darwin_amd64 darwin_arm64 linux_amd64 linux_arm64 windows_amd64; do
    printf '%064d  bide_1.2.3_%s.tar.gz\n' "${#t}" "$t"
  done > "$tmp/checksums.txt"
  out=$(formula v1.2.3 "$tmp/checksums.txt")
  for want in 'version "1.2.3"' 'releases/download/v1.2.3/bide_1.2.3_linux_arm64.tar.gz' 'bin.install "bide"'; do
    grep -qF "$want" <<<"$out" || { echo "self-test: the formula lacks $want"; ok=false; }
  done
  [ "$(grep -c '^      sha256 "[0-9a-f]\{64\}"$' <<<"$out")" = 4 ] || { echo "self-test: the formula does not pin four sha256s"; ok=false; }
  grep -q windows <<<"$out" && { echo "self-test: the formula names a Windows archive"; ok=false; }
  # A checksums file missing an archive is refused, not written with an empty sha256.
  grep -v linux_arm64 "$tmp/checksums.txt" > "$tmp/short.txt"
  # (Run as its own process: set -e does not apply inside an if condition.)
  if bash "$0" v1.2.3 "$tmp/short.txt" >/dev/null 2>&1; then echo "self-test: a missing archive was accepted"; ok=false; fi
  rm -rf "$tmp"
  $ok && echo "self-test: ok"
  $ok
}

case "${1:-}" in
  --self-test) self_test; exit ;;
  ""|-h|--help) sed -n '2,6p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
[ $# -eq 2 ] || die "usage: brew-formula.sh vX.Y.Z CHECKSUMS"
[[ "$1" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "$1 is not a release tag like v0.14.0"
[ -f "$2" ] || die "$2 does not exist"
out=$(formula "$1" "$2") || exit 1
echo "$out"
