package main

import (
	"bytes"
	"flag"
	"os"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "rewrite docs/reference/bide-hsm.md from the commands' help")

// referencePath is the generated reference, relative to this directory.
const referencePath = "../../../docs/reference/bide-hsm.md"

// TestReference: docs/reference/bide-hsm.md is what the commands print for -h, so the page cannot
// drift from the flags. Regenerate with go test . -run TestReference -update in cmd/bide/bide-hsm.
func TestReference(t *testing.T) {
	got := reference(t)
	if *update {
		if err := os.WriteFile(referencePath, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(referencePath)
	if err != nil {
		t.Fatalf("%v (generate it with go test . -run TestReference -update in cmd/bide/bide-hsm)", err)
	}
	// A Windows checkout may hold the page with CRLF line endings (core.autocrlf); compare the text.
	if strings.ReplaceAll(string(want), "\r\n", "\n") != got {
		t.Fatalf("%s is out of date: run go test . -run TestReference -update in cmd/bide/bide-hsm and commit the result", referencePath)
	}
}

// help runs bide-hsm with args and returns what it printed.
func help(t *testing.T, args ...string) string {
	t.Helper()
	var out, errb bytes.Buffer
	if code := run(args, strings.NewReader(""), &out, &errb, deps{}); code != 0 {
		t.Fatalf("%v: exit %d\n%s", args, code, errb.String())
	}
	return out.String() + errb.String()
}

func reference(t *testing.T) string {
	var b strings.Builder
	b.WriteString("# bide-hsm command reference\n\n")
	b.WriteString(`<!-- Generated by TestReference in cmd/bide/bide-hsm from what the commands print for -h. Do not edit:
     run go test . -run TestReference -update in cmd/bide/bide-hsm. CI fails when this page is stale. -->

bide-hsm is [bide approve](cli.md#bide-approve) for approvers whose signing keys are in an HSM, on a
smart card or token, or in a cloud KMS. It is a separate program because the PKCS#11 library it loads
needs cgo, and the ` + "`bide`" + ` command is built without it. It is not in the release archives: build it
from source (it needs a C compiler for PKCS#11 keys; without cgo it builds and still signs with a KMS key):

` + "```sh\nCGO_ENABLED=1 go install github.com/bide-ai/bide/cmd/bide/bide-hsm@latest\n```" + `

Key custody is explained in [the key custody guide](../guides/key-custody.md#approver-keys); the
approval flow in [Human approval](../guides/hitl-approval.md). Flags take one dash, as in ` + "`bide`" + `.
Exit status is 0 for success, 1 for a refusal or a failure, and 2 for a usage error.

| Command | What it does |
|---|---|
| [` + "`bide-hsm approve`" + `](#bide-hsm-approve) | record your signed approval (or -reject) of a call that waits for a decision, with a key in an HSM or KMS; -list shows what waits |
| [` + "`bide-hsm pubkey`" + `](#bide-hsm-pubkey) | print the public key of a key in an HSM or KMS, and the approver-keys entry that enrols it |
| [` + "`bide-hsm version`" + `](#bide-hsm-version) | print the version and whether this build can use PKCS#11 keys |
`)
	for _, c := range []struct{ name, h string }{
		{"approve", help(t, "approve", "-h")},
		{"pubkey", help(t, "pubkey", "-h")},
	} {
		b.WriteString("\n## bide-hsm " + c.name + "\n\n```text\n" + c.h + "```\n")
	}
	b.WriteString("\n## bide-hsm version\n\n```text\nusage: bide-hsm version\n```\n\nPrints `bide-hsm <version>` and whether the build can use PKCS#11 keys (built with cgo) or only KMS keys.\n")
	b.WriteString("\n## bide-hsm help\n\n```text\n" + help(t, "help") + "```\n")
	return b.String()
}
