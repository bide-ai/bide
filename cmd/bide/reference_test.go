//go:build !bide_audit_only

package main

import (
	"flag"
	"fmt"
	"os"
	"strings"
	"testing"

	"github.com/bide-ai/bide/internal/auditcli"
)

var update = flag.Bool("update", false, "rewrite docs/reference/cli.md from the commands' flag sets")

// referencePath is the generated CLI reference, relative to this directory.
const referencePath = "../../docs/reference/cli.md"

// TestCLIReference: docs/reference/cli.md is what the commands print for help: every command and
// audit verb, each with the usage and flags its own flag set prints (FlagSet.PrintDefaults) and its
// exit statuses. It fails when a flag, a default or a usage string changes and the page was not
// regenerated, so the reference cannot drift. Regenerate with
//
//	go test ./cmd/bide -run TestCLIReference -update   (from the cmd/bide module: go test . -run ...)
func TestCLIReference(t *testing.T) {
	got := reference()
	if *update {
		if err := os.WriteFile(referencePath, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(referencePath)
	if err != nil {
		t.Fatalf("%v (generate it with go test . -run TestCLIReference -update in cmd/bide)", err)
	}
	// A Windows checkout may hold the page with CRLF line endings (core.autocrlf); compare the text.
	if strings.ReplaceAll(string(want), "\r\n", "\n") != got {
		t.Fatalf("%s is out of date: run go test . -run TestCLIReference -update in cmd/bide and commit the result", referencePath)
	}
}

// reference renders the CLI reference page.
func reference() string {
	var b strings.Builder
	b.WriteString(`# bide command reference

<!-- Generated by TestCLIReference in cmd/bide from the flag sets the commands parse. Do not edit:
     run go test . -run TestCLIReference -update in cmd/bide. CI fails when this page is stale. -->

One program, ` + "`bide`" + `, for everyone who does not import the library. Install it with
` + "`brew install bide-ai/tap/bide`" + ` or ` + "`go install github.com/bide-ai/bide/cmd/bide@latest`" + `.

Every command parses its own flags with the standard library ` + "`flag`" + ` package: flags take
one dash (` + "`-db`" + `, ` + "`-evidence`" + `), and ` + "`bide help <command>`" + ` or
` + "`bide <command> -h`" + ` prints what is below. Exit status is 0 for success, 1 for a failure and
2 for a usage error, for every command but ` + "`bide audit`" + `, which keeps its own statuses:
only 0 means verified.

Built with ` + "`-tags bide_audit_only`" + `, the program holds only ` + "`audit`" + `, ` + "`version`" + `
and ` + "`help`" + `, and its import graph is the standard library and the core module (see the
[security model](../guides/security-model.md)).

`)
	b.WriteString("| Command | What it does |\n|---|---|\n")
	for _, c := range commands {
		fmt.Fprintf(&b, "| [`bide %s`](#bide-%s) | %s |\n", c.name, c.name, c.summary)
	}
	for _, c := range commands {
		fmt.Fprintf(&b, "\n## bide %s\n\n%s.\n\n```text\n%s```\n", c.name, capitalize(c.summary), commandHelp(c, nil))
		if c.name != "audit" {
			continue
		}
		for _, v := range auditcli.Verbs() {
			fmt.Fprintf(&b, "\n### bide audit %s\n\n```text\n%s```\n", v, commandHelp(c, []string{v}))
		}
	}
	return b.String()
}

func capitalize(s string) string { return strings.ToUpper(s[:1]) + s[1:] }
