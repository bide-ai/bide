func styleOf(t *testing.T, h http.Handler) string {
	t.Helper()
	code, body := get(t, h, "/assets/style.css")
	if code != 200 {
		t.Fatalf("GET /assets/style.css = %d: %s", code, body)
	}
	return body
}

func customTheme(t *testing.T) *theme.Theme {
	t.Helper()
	data, _ := json.Marshal(map[string]any{"bide_theme": 1, "name": "acme-night", "base": "dark", "surface": map[string]any{"bg": "#0e1116", "accent": "#79b8ff"}})
	th, _, err := theme.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	return th
}

// TestStyleCarriesTheThemes: the viewer serves style.css as the generated theme stylesheet followed
// by the file, so every page has its tokens from the checked themes.
func TestStyleCarriesTheThemes(t *testing.T) {
	css := styleOf(t, Handler(Options{Config: &Config{}}))
	if !strings.HasPrefix(css, "/* Generated by bide") {
		t.Errorf("style.css does not start with the generated themes: %.60s", css)
	}
	for _, want := range []string{
		`--bide-themes: "light dark high-contrast";`, `:root[data-theme="high-contrast"] {`,
		"@media (prefers-color-scheme: dark) {\n:root:not([data-theme]) {", "--good: #226d3b;", "* { box-sizing: border-box; }",
	} {
		if !strings.Contains(css, want) {
			t.Errorf("style.css lacks %q", want)
		}
	}
	raw, err := os.ReadFile("assets/style.css")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasSuffix(css, string(raw)) {
		t.Error("style.css does not end with the embedded file")
	}
	// The embedded file defines no colour, space, type or radius token: the themes do.
	if m := regexp.MustCompile(`--(?:bg|card|fg|good|bad|warn|accent|gate|idle|side|idem|line|muted|s[1-7]|t-\w+|r-\w+|shadow|font|mono|j-\w+):`).Find(raw); m != nil {
		t.Errorf("assets/style.css defines %s; tokens come from the themes", m)
	}
}

func TestCustomThemeAndDefault(t *testing.T) {
	th := customTheme(t)
	css := styleOf(t, Handler(Options{Config: &Config{}, Themes: []*theme.Theme{th}}))
	if !strings.Contains(css, `"light dark high-contrast acme-night"`) || !strings.Contains(css, `:root[data-theme="acme-night"] {`) || !strings.Contains(css, "--bg: #0e1116;") {
		t.Error("the custom theme is not in the stylesheet")
	}
	css = styleOf(t, Handler(Options{Config: &Config{}, Themes: []*theme.Theme{th}, DefaultTheme: "acme-night"}))
	if !strings.Contains(css, `--bide-default: "acme-night";`) || strings.Contains(css, "@media (prefers-color-scheme") {
		t.Error("a default theme leaves the system setting in charge")
	}
}

// TestAssetsServed: other assets are served as before, style.css can be ranged and is text/css, and
// Assets (what the editor serves) carries the themes too.
func TestAssetsServed(t *testing.T) {
	h := Handler(Options{Config: &Config{}})
	for name, typ := range map[string]string{"style.css": "text/css", "graph.css": "text/css", "theme.js": "text/javascript"} {
		req := httptest.NewRequest("GET", "/assets/"+name, nil)
		req.Host = "127.0.0.1:8484"
		rec := httptest.NewRecorder()
		h.ServeHTTP(rec, req)
		if rec.Code != 200 || !strings.HasPrefix(rec.Header().Get("Content-Type"), typ) {
			t.Errorf("%s: %d %q", name, rec.Code, rec.Header().Get("Content-Type"))
		}
	}
	req := httptest.NewRequest("GET", "/assets/style.css", nil)
	req.Host = "127.0.0.1:8484"
	req.Header.Set("Range", "bytes=0-9")
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, req)
	if rec.Code != 206 || rec.Body.Len() != 10 {
		t.Errorf("a range request: %d, %d bytes", rec.Code, rec.Body.Len())
	}
	b, err := readFS("style.css")
	if err != nil || !bytes.HasPrefix(b, []byte("/* Generated by bide")) {
		t.Errorf("Assets() style.css: %v %.40s", err, b)
	}
	if b, err := readFS("theme.js"); err != nil || bytes.Contains(b, []byte("Generated by bide")) {
		t.Errorf("Assets() theme.js: %v", err)
	}
}

func readFS(name string) ([]byte, error) {
	f, err := Assets().Open(name)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	return io.ReadAll(f)
}

// TestHeadLoadsStylesFirst: the theme script reads the theme list from the stylesheet, so the page
// links style.css before it.
func TestHeadLoadsStylesFirst(t *testing.T) {
	_, page := get(t, Handler(Options{Config: &Config{}}), "/")
	css, js := strings.Index(page, `href="/assets/style.css"`), strings.Index(page, `src="/assets/theme.js"`)
	if css < 0 || js < 0 || css > js {
		t.Errorf("style.css at %d, theme.js at %d: the stylesheet must come first", css, js)
	}
	if !strings.Contains(page, `id="theme-status" class="sr-only" role="status" aria-live="polite"`) {
		t.Error("the page has no live region for the theme change")
	}
	if !strings.Contains(page, `aria-label="Switch theme"`) {
		t.Error("the theme button is not labelled")
	}
}

func writeThemeFile(t *testing.T, over map[string]any) string {
	t.Helper()
	m := map[string]any{"bide_theme": 1, "name": "acme-night", "base": "dark"}
	for k, v := range over {
		m[k] = v
	}
	data, _ := json.Marshal(m)
	p := filepath.Join(t.TempDir(), "theme.json")
	if err := os.WriteFile(p, data, 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

// TestMainThemeFlags: a theme file that fails its checks is refused before anything is served, a
// default that names no theme and flags with -check are usage errors, and a good file is served.
func TestMainThemeFlags(t *testing.T) {
	cfg := filepath.Join(t.TempDir(), "flow.json")
	if err := os.WriteFile(cfg, []byte(`{"version":1,"name":"f","nodes":[],"edges":[]}`), 0o644); err != nil {
		t.Fatal(err)
	}
	run := func(args ...string) (int, string) {
		var out, errb bytes.Buffer
		return Main(args, &out, &errb, Stores{}), errb.String()
	}
	bad := writeThemeFile(t, map[string]any{"surface": map[string]any{"text": "#121214"}})
	if code, errs := run("-config", cfg, "-theme", bad); code != 1 || !strings.Contains(errs, "C1 text on bg") {
		t.Errorf("a failing theme: exit %d, stderr %q", code, errs)
	}
	if code, errs := run("-config", cfg, "-theme", filepath.Join(t.TempDir(), "missing.json")); code != 1 || errs == "" {
		t.Errorf("a missing theme file: exit %d, stderr %q", code, errs)
	}
	// A flag error is a usage error whatever the theme file holds.
	if code, _ := run("-theme", bad); code != 2 {
		t.Errorf("a bad -theme with no input: exit %d, want the usage error 2", code)
	}
	good := writeThemeFile(t, nil)
	if code, errs := run("-config", cfg, "-theme", good, "-theme-default", "neon"); code != 2 || !strings.Contains(errs, "names no theme") {
		t.Errorf("an unknown default: exit %d, stderr %q", code, errs)
	}
	if code, errs := run("-config", cfg, "-check", "-theme", good); code != 2 || !strings.Contains(errs, "-check serves none") {
		t.Errorf("-theme with -check: exit %d, stderr %q", code, errs)
	}
	if code, _ := run("-config", cfg, "-check", "-theme-default", "dark"); code != 2 {
		t.Errorf("-theme-default with -check: exit %d", code)
	}
	// Which checks refuse: the format, and every contrast, distinctness and polarity check.
	for name, over := range map[string]map[string]any{
		"C1 text contrast":    {"surface": map[string]any{"text": "#121214"}},
		"C2 control edge":     {"surface": map[string]any{"border_strong": "#25252a"}},
		"C3 status colours":   {"semantic": map[string]any{"warning": map[string]any{"fg": "#f89487"}}},
		"C4 domain colours":   {"semantic": map[string]any{"idem": map[string]any{"fg": "#92b8f6"}}},
		"C8 polarity":         {"semantic": map[string]any{"alert": map[string]any{"fg": "#7ad3a4"}, "ok": map[string]any{"fg": "#f89487"}}},
		"a key outside C7":    {"scrim": 0.9},
		"an unknown key":      {"fonts": "x"},
		"a colour that isn't": {"surface": map[string]any{"bg": "red"}},
	} {
		if code, errs := run("-config", cfg, "-theme", writeThemeFile(t, over)); code != 1 || errs == "" {
			t.Errorf("%s: exit %d, stderr %q; want the theme refused", name, code, errs)
		}
	}
	// C6 alone only warns: the theme is served, and the warning names the pair.
	cb := writeThemeFile(t, map[string]any{"base": "light", "name": "acme-day", "semantic": map[string]any{
		"ok": map[string]any{"fg": "#1b6a32"}, "warning": map[string]any{"fg": "#835400"}, "alert": map[string]any{"fg": "#b0241c"},
	}})
	code, _, errs := serveMain(t, []string{"-config", cfg, "-theme", cb}, func(base string) {
		resp, err := http.Get(base + "assets/style.css")
		if err != nil {
			t.Error(err)
			return
		}
		defer resp.Body.Close()
		b, _ := io.ReadAll(resp.Body)
		if !strings.Contains(string(b), `:root[data-theme="acme-day"]`) {
			t.Error("a theme with only a colour-blindness warning is not served")
		}
	})
	if code != 0 || !strings.Contains(errs, "warning C6") {
		t.Errorf("a C6-only theme: exit %d, stderr %q; want it served with a C6 warning", code, errs)
	}
	code, _, errs = serveMain(t, []string{"-config", cfg, "-theme", good, "-theme-default", "acme-night"}, func(base string) {
		css, err := http.Get(base + "assets/style.css")
		if err != nil {
			t.Error(err)
			return
		}
		defer css.Body.Close()
		b, _ := io.ReadAll(css.Body)
		if !strings.Contains(string(b), `--bide-default: "acme-night";`) || !strings.Contains(string(b), `:root[data-theme="acme-night"]`) {
			t.Errorf("the served style.css lacks the theme file's theme or default: %.200s", b)
		}
	})
	if code != 0 {
		t.Errorf("serving with a theme: exit %d, stderr %q", code, errs)
	}
	// A shipped name is a valid default.
	if code, _, errs := serveMain(t, []string{"-config", cfg, "-theme-default", "high-contrast"}, func(base string) {}); code != 0 {
		t.Errorf("a shipped default: exit %d, stderr %q", code, errs)
	}
}

// TestToggleUsesThemeScript: the header button and the t key step through the stylesheet's theme
// list through theme.js, not through a light-or-dark test of their own.
func TestToggleUsesThemeScript(t *testing.T) {
	b, err := os.ReadFile("assets/view.js")
	if err != nil {
		t.Fatal(err)
	}
	js := string(b)
	if !strings.Contains(js, "window.bideTheme.toggle()") || strings.Contains(js, `"prefers-color-scheme: dark"`) || strings.Contains(js, `=== "dark"`) {
		t.Error("view.js does not toggle through theme.js, or still tests for dark itself")
	}
}
