var update = flag.Bool("update", false, "rewrite testdata/themes.css.golden")

// grammar is the whole language of the generated stylesheet: every line of CSS must match one of
// these patterns. Values are colours, pixel lengths, the fixed shadow, scrim and font tables, and
// two keywords; there is no selector but the five fixed shapes, no URL and no function except rgb()
// in a shadow and the scrim.
var grammar = func() *regexp.Regexp {
	alt := func(ss ...string) string {
		for i, s := range ss {
			ss[i] = regexp.QuoteMeta(s)
		}
		return strings.Join(ss, "|")
	}
	var fonts, shadows []string
	for _, f := range fontStacks {
		fonts = append(fonts, f)
	}
	for _, lvl := range shadowNames {
		for _, dark := range []bool{false, true} {
			shadows = append(shadows, shadowValue(lvl, dark))
		}
	}
	value := `#[0-9a-f]{6}|[0-9]+(?:\.[0-9]+)?px|rgb\(0 0 0 / 0\.[0-9]{2}\)|` + alt(fonts...) + `|` + alt(shadows...)
	return regexp.MustCompile(`^(?:` +
		regexp.QuoteMeta(`/* Generated by bide from the checked themes. Do not edit. */`) +
		`|:root \{|:root:not\(\[data-theme\]\) \{|@media \(prefers-color-scheme: dark\) \{|:root\[data-theme="[a-z][a-z0-9-]{1,31}"\] \{|\}` +
		`|  --[a-z0-9-]+: (?:` + value + `);` +
		`|  --bide-themes: "[a-z0-9 -]+";` +
		`|  color-scheme: (?:light|dark);` +
		`)$`)
}()

func checkGrammar(t testing.TB, css string) {
	t.Helper()
	if !strings.HasSuffix(css, "\n") {
		t.Fatalf("CSS does not end in a newline")
	}
	for _, line := range strings.Split(strings.TrimSuffix(css, "\n"), "\n") {
		if !grammar.MatchString(line) {
			t.Fatalf("CSS line outside the grammar: %q", line)
		}
	}
}

func TestShippedCSS(t *testing.T) {
	css := CSS(Shipped())
	checkGrammar(t, css)
	const golden = "testdata/themes.css.golden"
	if *update {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(golden, []byte(css), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatalf("%v (go test ./internal/theme -run TestShippedCSS -update)", err)
	}
	if string(want) != css {
		t.Errorf("generated CSS differs from %s; if the change is intended, go test ./internal/theme -run TestShippedCSS -update", golden)
	}
	if CSS(Shipped()) != css {
		t.Error("CSS is not deterministic")
	}
	if CSS(nil) != "" {
		t.Error("CSS of no themes is not empty")
	}
}

func TestCSSShape(t *testing.T) {
	css := CSS(Shipped())
	for _, want := range []string{
		":root {\n", `--bide-themes: "light dark high-contrast";`,
		"@media (prefers-color-scheme: dark) {\n:root:not([data-theme]) {\n",
		`:root[data-theme="light"] {`, `:root[data-theme="dark"] {`, `:root[data-theme="high-contrast"] {`,
		"--good: #226d3b;", "--good-bg: #e0f1e5;", "--bad: #94201c;", "--warn: #8c5900;", "--card-2: #efefea;", "--line-strong: #7d7d74;",
		"--info: #1b52b0;", "--on-sem: #ffffff;", "--on-accent: #ffffff;", "--j-key: #1b52b0;",
		"--t-sm: 13.5px;", "--s5: 24px;", "--r-md: 10px;", "--scrim: rgb(0 0 0 / 0.45);",
		"--shadow: 0 1px 2px rgb(0 0 0 / .06), 0 4px 14px rgb(0 0 0 / .05);", "color-scheme: dark;",
	} {
		if !strings.Contains(css, want) {
			t.Errorf("CSS lacks %q", want)
		}
	}
	// The default block is the light theme's, and the media block is the dark theme's.
	root := css[:strings.Index(css, "@media")]
	if !strings.Contains(root, "--bg: #f6f6f2;") || strings.Contains(root, "color-scheme: dark") {
		t.Error(":root is not the light theme")
	}
	media := css[strings.Index(css, "@media"):strings.Index(css, ":root[data-theme")]
	if !strings.Contains(media, "--bg: #121214;") {
		t.Error("the prefers-color-scheme block is not the dark theme")
	}
}

func TestCSSDensityAndScale(t *testing.T) {
	th, _, err := Parse(custom("light", map[string]any{"density": "compact", "type_scale": 1.25}))
	if err != nil {
		t.Fatal(err)
	}
	css := CSS([]*Theme{th})
	for _, want := range []string{"--s1: 3.4px;", "--s7: 40.8px;", "--t-md: 19.38px;", "--t-xs: 15px;"} {
		if !strings.Contains(css, want) {
			t.Errorf("CSS lacks %q", want)
		}
	}
	checkGrammar(t, css)
}

func TestCSSCustomTheme(t *testing.T) {
	th, _, err := Parse(custom("dark", map[string]any{"surface": map[string]any{"bg": "#0e1116"}}))
	if err != nil {
		t.Fatal(err)
	}
	css := CSS(append(Shipped(), th))
	checkGrammar(t, css)
	if !strings.Contains(css, `:root[data-theme="acme-test"] {`) || !strings.Contains(css, `"light dark high-contrast acme-test"`) {
		t.Error("custom theme is not in the stylesheet")
	}
}

// FuzzParseCSS: whatever bytes Parse accepts, the CSS built from the result stays inside the
// grammar. This is the wall against CSS injection.
func FuzzParseCSS(f *testing.F) {
	for _, n := range shippedNames {
		data, _ := shippedFS.ReadFile("themes/" + n + ".json")
		f.Add(data)
	}
	f.Add(custom("dark", map[string]any{"surface": map[string]any{"bg": "#0e1116"}, "density": "roomy", "scrim": 0.5}))
	f.Add([]byte(`{"bide_theme":1,"name":"a-b","base":"light","surface":{"bg":"#fff"},"font_ui":"humanist"}`))
	f.Fuzz(func(t *testing.T, data []byte) {
		th, _, err := Parse(data)
		if err != nil {
			return
		}
		checkGrammar(t, CSS(append(Shipped(), th)))
	})
}
