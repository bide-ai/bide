package theme

import (
	"strconv"
	"strings"
)

// typeSizes and spaceSizes are the pages' scales at scale 1 and normal density, in px.
var (
	typeSizes  = []struct{ name, px string }{{"--t-xs", "12"}, {"--t-sm", "13.5"}, {"--t-md", "15.5"}, {"--t-lg", "18"}, {"--t-xl", "24"}, {"--t-2xl", "36"}, {"--t-hero", "36"}}
	spaceSizes = []struct{ name, px string }{{"--s1", "4"}, {"--s2", "8"}, {"--s3", "12"}, {"--s4", "16"}, {"--s5", "24"}, {"--s6", "32"}, {"--s7", "48"}}
)

func px(base string, factor float64) string {
	v, _ := strconv.ParseFloat(base, 64)
	return strconv.FormatFloat(round2(v*factor), 'f', -1, 64) + "px"
}

// declarations returns the custom properties of t, one "--name: value;" per line, in a fixed order.
// Every value is built from the theme's parsed fields in canonical form or taken from a table in
// this package: nothing a user wrote is copied.
func (t *Theme) declarations() []string {
	var d []string
	add := func(name, value string) { d = append(d, name+": "+value+";") }
	for _, s := range slots {
		for _, n := range s.css {
			add(n, t.c[s.path].String())
		}
	}
	add("--shadow", shadowValue(t.shadow, t.Dark()))
	add("--scrim", "rgb(0 0 0 / "+strconv.FormatFloat(round2(t.scrim), 'f', 2, 64)+")")
	add("--font", fontStacks[t.fontUI])
	add("--mono", fontStacks[t.fontMono])
	for _, s := range typeSizes {
		add(s.name, px(s.px, t.typeScale))
	}
	for _, s := range spaceSizes {
		add(s.name, px(s.px, densityFactor[t.density]))
	}
	for i, n := range []string{"--r-sm", "--r-md", "--r-lg"} {
		add(n, strconv.Itoa(t.radius[i])+"px")
	}
	if t.Dark() {
		add("color-scheme", "dark")
	} else {
		add("color-scheme", "light")
	}
	return d
}

func writeBlock(b *strings.Builder, selector string, decls []string, extra ...string) {
	b.WriteString(selector + " {\n")
	for _, d := range decls {
		b.WriteString("  " + d + "\n")
	}
	for _, e := range extra {
		b.WriteString("  " + e + "\n")
	}
	b.WriteString("}\n")
}

// CSS is the stylesheet for a set of checked themes: the theme called light (or, if none is, the
// first) as the :root default, the theme called dark under prefers-color-scheme when the page set
// no data-theme, and one :root[data-theme="name"] block per theme. --bide-themes lists the names for
// the page's script. The whole output is a fixed template filled with values the package built, so
// a theme can add no selector, property, URL or function to it.
func CSS(themes []*Theme) string { return CSSDefault(themes, "") }

// CSSDefault is CSS with a default theme: the one named def (a name in themes) is the :root block
// and the page's start, and the prefers-color-scheme block is left out, so the reader's system
// setting no longer picks the start; --bide-default carries the name to the page's script. An
// empty def is CSS. A def that names no theme in themes panics, as an unchecked theme does: it is a
// host error.
func CSSDefault(themes []*Theme, def string) string {
	if len(themes) == 0 {
		return ""
	}
	seen := map[string]bool{}
	for _, t := range themes {
		if !t.checked {
			panic("theme: CSS of a theme that did not come from Parse or Shipped")
		}
		if seen[t.name] {
			panic("theme: CSS given two themes named " + t.name)
		}
		seen[t.name] = true
	}
	root := themes[0]
	var dark, contrast *Theme
	names := make([]string, len(themes))
	found := def == ""
	for i, t := range themes {
		names[i] = t.name
		switch t.name {
		case "light":
			root = t
		case "dark":
			dark = t
		case "high-contrast":
			contrast = t
		}
		if t.name == def {
			found = true
		}
	}
	if !found {
		panic("theme: CSS default " + def + " is not among the themes")
	}
	extra := []string{`--bide-themes: "` + strings.Join(names, " ") + `";`}
	if def != "" {
		for _, t := range themes {
			if t.name == def {
				root = t
			}
		}
		dark = nil
		extra = append(extra, `--bide-default: "`+def+`";`)
	}
	var b strings.Builder
	b.WriteString("/* Generated by bide from the checked themes. Do not edit. */\n")
	writeBlock(&b, ":root", root.declarations(), extra...)
	if dark != nil {
		b.WriteString("@media (prefers-color-scheme: dark) {\n")
		var inner strings.Builder
		writeBlock(&inner, ":root:not([data-theme])", dark.declarations())
		b.WriteString(inner.String())
		b.WriteString("}\n")
	}
	if contrast != nil {
		// A reader who asks the system for more contrast gets the high-contrast theme, over the
		// dark one and over a host's default, unless they chose a theme in the page (data-theme).
		b.WriteString("@media (prefers-contrast: more) {\n")
		var inner strings.Builder
		writeBlock(&inner, ":root:not([data-theme])", contrast.declarations())
		b.WriteString(inner.String())
		b.WriteString("}\n")
	}
	for _, t := range themes {
		writeBlock(&b, `:root[data-theme="`+t.name+`"]`, t.declarations())
	}
	// Forced colors: the system's colors win over every theme, a host's default and a reader's
	// choice. The block comes last and is as specific as the theme blocks, so it beats them all.
	b.WriteString("@media (forced-colors: active) {\n")
	var forced strings.Builder
	writeBlock(&forced, ":root:root, :root[data-theme]", forcedDeclarations())
	b.WriteString(forced.String())
	b.WriteString("}\n")
	return b.String()
}

// forcedColors maps each color slot to the system color that carries its role when the system
// forces colors: the ground is Canvas, text and every state color are CanvasText (the system offers
// one text color, so a state is told by its shape, glyph and words), links and the info color are
// LinkText, quiet strokes and borders GrayText, the control edge ButtonBorder, the focus ring
// Highlight. docs/design/themes.md has the table and the reasons.
var forcedColors = map[string]string{
	"surface.bg": "Canvas", "surface.surface": "Canvas", "surface.surface2": "Canvas", "surface.canvas_bg": "Canvas", "surface.node_fill": "Canvas",
	"surface.text": "CanvasText", "surface.muted": "CanvasText", "surface.border": "GrayText", "surface.border_strong": "ButtonBorder",
	"surface.accent": "LinkText", "surface.accent_bg": "Canvas", "surface.on_accent": "Canvas", "surface.focus": "Highlight",
	"semantic.ok.fg": "CanvasText", "semantic.warning.fg": "CanvasText", "semantic.alert.fg": "CanvasText", "semantic.gated.fg": "CanvasText",
	"semantic.effect.fg": "CanvasText", "semantic.idem.fg": "CanvasText", "semantic.info.fg": "LinkText", "semantic.idle.fg": "GrayText", "semantic.on.fg": "Canvas",
	"semantic.ok.bg": "Canvas", "semantic.warning.bg": "Canvas", "semantic.alert.bg": "Canvas", "semantic.gated.bg": "Canvas",
	"semantic.effect.bg": "Canvas", "semantic.idem.bg": "Canvas", "semantic.info.bg": "Canvas",
	"syntax.key": "CanvasText", "syntax.str": "CanvasText", "syntax.num": "CanvasText", "syntax.bool": "CanvasText", "syntax.null": "GrayText", "syntax.punct": "GrayText",
}

// forcedDeclarations are the custom properties of the forced-colors block: the colors above, no
// shadow, and the dark-or-light of the system (color-scheme is left to the system).
func forcedDeclarations() []string {
	var d []string
	for _, s := range slots {
		for _, n := range s.css {
			d = append(d, n+": "+forcedColors[s.path]+";")
		}
	}
	return append(d, "--shadow: none;")
}
