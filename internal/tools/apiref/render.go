package apiref

import (
	"fmt"
	"regexp"
	"strings"
)

// PageDir is the directory of the generated pages, relative to the repository root.
const PageDir = "docs/reference/api"

const header = `<!-- Generated by TestAPIReference in internal/tools/apiref from the Go sources. Do not edit:
     run go test ./internal/tools/apiref -run TestAPIReference -update from the repository root.
     CI fails when this page is stale. -->
`

// Render returns the pages, keyed by file name under PageDir: index.md and one page per module.
// It assigns each package its label and fails when a package has none.
func Render(mods []*Module, cfg Config) (map[string]string, error) {
	for _, m := range mods {
		for _, p := range m.Packages {
			l, ok := cfg.Labels[p.Rel]
			if !ok {
				return nil, fmt.Errorf("package %s has no stability label: add it to Labels in internal/tools/apiref/labels.go and to the table in docs/trust/stability.md", p.ImportPath)
			}
			p.Label = l
		}
	}
	pages := map[string]string{"index.md": renderIndex(mods)}
	for _, m := range mods {
		for _, pg := range pagesOf(m) {
			if _, dup := pages[pg.name]; dup {
				return nil, fmt.Errorf("two pages are called %s", pg.name)
			}
			pages[pg.name] = renderPage(pg, cfg)
		}
	}
	return pages, nil
}

// A page is one generated file: one module, or for the core module (too large for one page) one
// package.
type page struct {
	name string // file name
	mod  *Module
	pkgs []*Package
	one  bool // the page is one package, whose heading is the page title
}

// pagesOf splits a module into its pages: the core module gets one page per package, every other
// module one page. The rule depends on the module only, not on its size, so page names never move
// as the API grows.
func pagesOf(m *Module) []page {
	if m.Dir != "." {
		return []page{{name: m.Slug() + ".md", mod: m, pkgs: m.Packages}}
	}
	var out []page
	for _, p := range m.Packages {
		out = append(out, page{name: strings.ReplaceAll(p.Rel, "/", "-") + ".md", mod: m, pkgs: []*Package{p}, one: true})
	}
	return out
}

func renderIndex(mods []*Module) string {
	var b strings.Builder
	b.WriteString("# SDK API reference\n\n" + header + `
Every exported constant, variable, function and type of every package in the published bide modules,
with its declaration and the first sentence of its doc comment. It is generated from the Go sources,
so it cannot drift from them; the full documentation of a symbol is its doc comment, on
[pkg.go.dev](https://pkg.go.dev/github.com/bide-ai/bide) or in the source. The ports and how to
implement them are in [extension points](../extension-points.md); the module layout is in
[module structure](../module-structure.md).

Packages are listed for linux/amd64 with cgo enabled. Packages under ` + "`internal/`" + `, the ` + "`bide`" + ` and
` + "`bide-hsm`" + ` programs, the examples and the repo-only test modules are not part of the API and are not listed.

## Stability labels

Each package carries one label, declared in one place and checked against
[stability and support](../../trust/stability.md#package-stability), which says what each means:

- **` + Stable + `**: the package the library is built around; a change to it is announced as Breaking in the changelog.
- **` + Experimental + `**: new or still moving; it may change in any minor release.
- **` + BuildingBlock + `**: implemented and tested, but no approval gate calls it yet.

Pre-1.0, a minor version may include breaking changes in any package.

## Modules

| Module | Packages | Pages |
|---|---|---|
`)
	for _, m := range mods {
		pgs := pagesOf(m)
		where := fmt.Sprintf("[%s](%s)", m.Slug(), pgs[0].name)
		if pgs[0].one {
			where = "one page per package, listed below"
		}
		fmt.Fprintf(&b, "| `%s` | %d | %s |\n", m.Path, len(m.Packages), where)
	}
	b.WriteString("\n## Packages\n\n| Package | Stability | Synopsis |\n|---|---|---|\n")
	for _, m := range mods {
		for _, p := range m.Packages {
			link := pagesOf(m)[0].name
			if pagesOf(m)[0].one {
				link = strings.ReplaceAll(p.Rel, "/", "-") + ".md"
			}
			fmt.Fprintf(&b, "| [`%s`](%s) | %s | %s |\n", p.Rel, link, p.Label, cell(p.Synopsis))
		}
	}
	return b.String()
}

func renderPage(pg page, cfg Config) string {
	var b strings.Builder
	if pg.one {
		p := pg.pkgs[0]
		fmt.Fprintf(&b, "# Package `%s`\n\n%s\n", p.Rel, header)
		fmt.Fprintf(&b, "Go module `%s`; [all packages](index.md).\n", pg.mod.Path)
		renderPackage(&b, p, cfg, "", "##")
		return b.String()
	}
	fmt.Fprintf(&b, "# Module `%s`\n\n%s\n", pg.mod.Path, header)
	fmt.Fprintf(&b, "Go module `%s`; [all modules](index.md).\n", pg.mod.Path)
	for _, p := range pg.pkgs {
		renderPackage(&b, p, cfg, "## "+p.Rel, "###")
	}
	return b.String()
}

// renderPackage writes a package listing; heading is the package's own heading line (none on a
// page that is the package) and typeLevel the heading marker of its types.
func renderPackage(b *strings.Builder, p *Package, cfg Config, heading, typeLevel string) {
	if heading != "" {
		fmt.Fprintf(b, "\n%s\n", heading)
	}
	b.WriteString("\n")
	fmt.Fprintf(b, "`%s` · [pkg.go.dev](https://pkg.go.dev/%s) · Stability: **%s**\n\n", p.ImportPath, p.ImportPath, p.Label)
	fmt.Fprintf(b, "%s\n", text(p.Synopsis))
	section := func(title string, n int) bool {
		if n == 0 {
			return false
		}
		fmt.Fprintf(b, "\n**%s**\n\n", title)
		return true
	}
	if section("Constants", count(p.Consts)) {
		values(b, cfg, p, p.Consts, "const")
	}
	if section("Variables", count(p.Vars)) {
		values(b, cfg, p, p.Vars, "var")
	}
	if section("Functions", len(p.Funcs)) {
		entries(b, cfg, p, p.Funcs)
	}
	for _, t := range p.Types {
		fmt.Fprintf(b, "\n%s type %s\n\n", typeLevel, t.Name)
		fmt.Fprintf(b, "```go\n%s\n```\n\n%s%s\n", t.Decl, text(t.Sentence), tag(cfg, p, t.Name, t.File))
		if section("Constants", count(t.Consts)) {
			values(b, cfg, p, t.Consts, "const")
		}
		if section("Variables", count(t.Vars)) {
			values(b, cfg, p, t.Vars, "var")
		}
		if section("Constructors and functions", len(t.Funcs)) {
			entries(b, cfg, p, t.Funcs)
		}
		if section("Methods", len(t.Methods)) {
			entries(b, cfg, p, t.Methods)
		}
	}
}

func count(vs []Value) int {
	n := 0
	for _, v := range vs {
		n += len(v.Items)
	}
	return n
}

// tag is the note on a symbol whose label differs from its package's.
func tag(cfg Config, p *Package, name, file string) string {
	if l := cfg.labelOf(p, name, file); l != p.Label {
		return " *(" + l + ")*"
	}
	return ""
}

func entries(b *strings.Builder, cfg Config, p *Package, es []Entry) {
	for _, e := range es {
		fmt.Fprintf(b, "- `%s`: %s%s\n", oneLine(e.Decl), text(e.Sentence), tag(cfg, p, e.Name, e.File))
	}
}

// values lists the exported names of const or var groups, one per line with its type and, when
// it is short and explicit, its value.
func values(b *strings.Builder, cfg Config, p *Package, vs []Value, _ string) {
	for _, v := range vs {
		for i := 0; i < len(v.Items); {
			it := v.Items[i]
			// Names that share a sentence and a label are one line.
			specs := []string{it.Spec}
			j := i + 1
			for ; j < len(v.Items); j++ {
				n := v.Items[j]
				if n.Sentence != it.Sentence || cfg.labelOf(p, n.Name, n.File) != cfg.labelOf(p, it.Name, it.File) {
					break
				}
				specs = append(specs, n.Spec)
			}
			fmt.Fprintf(b, "- `%s`: %s%s\n", strings.Join(specs, "`, `"), text(it.Sentence), tag(cfg, p, it.Name, it.File))
			i = j
		}
	}
}

var space = regexp.MustCompile(`\s+`)

func oneLine(s string) string { return strings.TrimSpace(space.ReplaceAllString(s, " ")) }

// cell makes a sentence safe inside a table cell.
func cell(s string) string { return strings.ReplaceAll(text(s), "|", `\|`) }

var (
	docLink  = regexp.MustCompile(`\[([A-Za-z0-9_.*]+)\]`)
	codeSpan = regexp.MustCompile("`[^`]*`")
)

// text makes a doc sentence safe for Markdown and for Vue (VitePress compiles pages as Vue
// templates): [Name] doc links become code spans, and outside code spans the characters Markdown
// or HTML would interpret are escaped.
func text(s string) string {
	s = oneLine(s)
	s = docLink.ReplaceAllString(s, "`$1`")
	var out strings.Builder
	last := 0
	for _, loc := range codeSpan.FindAllStringIndex(s, -1) {
		out.WriteString(escape(s[last:loc[0]]))
		out.WriteString(s[loc[0]:loc[1]])
		last = loc[1]
	}
	out.WriteString(escape(s[last:]))
	return out.String()
}

var escaper = strings.NewReplacer(`\`, `\\`, "*", `\*`, "_", `\_`, "<", "&lt;", ">", "&gt;", "{{", "&#123;&#123;", "`", "\\`", "[", `\[`, "]", `\]`)

func escape(s string) string { return escaper.Replace(s) }
